/**
 * Local dev only: unlock a user and set a new password.
 *
 * Usage:
 *   node ./scripts/reset-local-user.mjs [email] [newPassword]
 *
 * Defaults: admin@dialyrounds.local / ChangeMe123!
 */
import { execSync } from 'node:child_process';
import { unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ITERATIONS = 100_000;
const __dirname = dirname(fileURLToPath(import.meta.url));

function toHex(buffer) {
  return [...new Uint8Array(buffer)].map((b) => b.toString(16).padStart(2, '0')).join('');
}

function fromHex(hex) {
  const bytes = new Uint8Array(hex.length / 2);
  for (let i = 0; i < hex.length; i += 2) {
    bytes[i / 2] = parseInt(hex.slice(i, i + 2), 16);
  }
  return bytes;
}

async function generateSalt() {
  const salt = crypto.getRandomValues(new Uint8Array(16));
  return toHex(salt.buffer);
}

async function hashPassword(password, saltHex) {
  const enc = new TextEncoder();
  const keyMaterial = await crypto.subtle.importKey(
    'raw',
    enc.encode(password),
    'PBKDF2',
    false,
    ['deriveBits']
  );
  const bits = await crypto.subtle.deriveBits(
    {
      name: 'PBKDF2',
      salt: fromHex(saltHex),
      iterations: ITERATIONS,
      hash: 'SHA-256',
    },
    keyMaterial,
    256
  );
  return toHex(bits);
}

function sqlString(value) {
  return `'${value.replace(/'/g, "''")}'`;
}

const email = process.argv[2] ?? 'admin@dialyrounds.local';
const password = process.argv[3] ?? 'ChangeMe123!';

if (password.length < 8) {
  console.error('Password must be at least 8 characters.');
  process.exit(1);
}

const salt = await generateSalt();
const passwordHash = await hashPassword(password, salt);

const sql = `-- generated by reset-local-user.mjs
UPDATE users
SET password_hash = ${sqlString(passwordHash)},
    salt = ${sqlString(salt)},
    failed_login_count = 0,
    locked_until = NULL,
    must_change_password = 0
WHERE lower(email) = lower(${sqlString(email)});`;

const sqlPath = join(__dirname, '.reset-user.sql');
writeFileSync(sqlPath, sql);

try {
  execSync(`wrangler d1 execute dialyrounds --local --file=${sqlPath}`, {
    cwd: join(__dirname, '..'),
    stdio: 'inherit',
  });
  console.log(`Reset password for ${email}. You can sign in with the new password.`);
} finally {
  unlinkSync(sqlPath);
}
